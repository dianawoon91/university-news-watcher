function articleHTML(article: NewsArticle, lang: 'en' | 'cn' = 'en'): string {
  const summary = lang === 'cn' ? article.summaryCn : article.summaryEn
  const source = article.source
  const date = new Date(article.scrapedAt).toLocaleDateString('en-US', { month: 'short', day: 'numeric' })

  return `
<div class="article">
  <div class="article-uni">${article.universityShortName}</div>
  <div class="article-title"><a href="${article.url}" target="_blank">${article.title}</a></div>
  <p class="article-summary">${summary}</p>
  <div class="article-meta">
    <span class="badge">${CATEGORY_LABELS[article.category]?.[lang] || article.category}</span>
    ${source} · ${date}
  </div>
</div>`
}

// ── Weekly Digest Email ───────────────────────────────────────────────────────

export async function sendWeeklyDigest(
  articles: NewsArticle[],
  config: AppConfig
): Promise<void> {
  if (!config.weeklyDigestEnabled) return

  const lang = config.defaultLanguage
  const dateRange = (() => {
    const end = new Date()
    const start = new Date()
    start.setDate(start.getDate() - 7)
    return `${start.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })} – ${end.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })}`
  })()

  const categoryOrder: NewsCategory[] = [
    'APPLICATION_POLICY', 'ADMISSIONS_STATS', 'POPULAR_MAJORS',
    'EXTRACURRICULAR', 'AI_TECHNOLOGY', 'INTERNATIONAL', 'OTHER_MARKETS', 'GENERAL'
  ]

  // Urgent first
  const urgentArticles = articles.filter((a) => a.urgency === 'URGENT')
  let body = ''

  if (urgentArticles.length > 0) {
    body += `<div class="section-title">🚨 Urgent Alerts</div>`
    body += urgentArticles.map((a) => articleHTML(a, lang)).join('')
  }

  // Then by category
  for (const cat of categoryOrder) {
    const catArticles = articles.filter((a) => a.category === cat && a.urgency !== 'URGENT')
    if (catArticles.length === 0) continue
    const label = CATEGORY_LABELS[cat]?.[lang] || cat
    body += `<div class="section-title">${label}</div>`
    body += catArticles.map((a) => articleHTML(a, lang)).join('')
  }

  if (!body) {
    body = '<p style="color:#999;text-align:center;">No articles found this week.</p>'
  }

  const subject = `Weekly University Admissions Digest — ${dateRange}`
  const html = emailWrapper(subject, body)

  await sendEmail({ to: config.recipients, subject, html }, config)
  console.log(`✅ Weekly digest sent to ${config.recipients.join(', ')}`)
}

// ── Urgent Alert Email ────────────────────────────────────────────────────────

export async function sendUrgentAlert(
  article: NewsArticle,
  config: AppConfig
): Promise<void> {
  if (!config.urgentAlertsEnabled) return

  const lang = config.defaultLanguage
  const summary = lang === 'cn' ? article.summaryCn : article.summaryEn

  const body = `
<div class="urgent-banner">
  <strong>🚨 Urgent Admissions Alert</strong>
  <p>${article.urgencyReason || 'This article has been flagged as urgent.'}</p>
</div>
<div class="article">
  <div class="article-uni">${article.universityName}</div>
  <div class="article-title"><a href="${article.url}">${article.title}</a></div>
  <p class="article-summary">${summary}</p>
  <div class="article-meta">
    Source: ${article.source} · ${new Date(article.scrapedAt).toLocaleString()}
  </div>
</div>`

  const subject = `URGENT: ${article.universityShortName} — ${article.title.slice(0, 60)}`
  const html = emailWrapper(subject, body)

  await sendEmail({ to: config.recipients, subject, html }, config)
  console.log(`✅ Urgent alert sent: ${article.title.slice(0, 60)}`)
}
