import { NewsArticle, AppConfig, CATEGORY_LABELS, NewsCategory } from './types'

interface EmailPayload {
  to: string[]
  subject: string
  html: string
}

async function getTransporter(config: AppConfig) {
  const nodemailer = await import('nodemailer')
  return nodemailer.default.createTransport({
    host: config.smtpHost,
    port: config.smtpPort,
    secure: config.smtpPort === 465,
    auth: {
      user: config.smtpUser,
      pass: config.smtpPass,
    },
  })
}

async function sendEmail(payload: EmailPayload, config: AppConfig): Promise<void> {
  if (!config.smtpUser || !config.smtpPass) {
    throw new Error('SMTP credentials not configured. Please set them in Settings.')
  }
  if (!payload.to.length) {
    throw new Error('No recipients configured. Please add recipients in Settings.')
  }

  const transporter = await getTransporter(config)
  await transporter.sendMail({
    from: `"University News Watcher" <${config.smtpUser}>`,
    to: payload.to.join(', '),
    subject: payload.subject,
    html: payload.html,
  })
}

